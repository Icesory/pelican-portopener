"""Build downloadable IPv4 release and importable Egg. No credentials included."""
import argparse
import hashlib
import json
import shutil
from pathlib import Path
import zipfile

root = Path(__file__).resolve().parents[1]


def build(download_url=''):
    version = json.loads((root / 'plugin/port-opener/plugin.json').read_text())['version']
    output = root / 'dist'
    output.mkdir(exist_ok=True)
    filename = f'port-opener-service-ipv4-{version}.zip'
    archive_path = output / filename
    with zipfile.ZipFile(archive_path, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name in ('port_opener.py', 'outbound.py', 'ipv6.py', 'diagnostics.py', 'diagnostics-schema.json', 'start_ipv4.py', 'LICENSE'):
            source = root / name if name == 'LICENSE' else root / ('packaging/egg' if name == 'start_ipv4.py' else 'service') / name
            # Fixed metadata and LF make the checksum reproducible on Windows/Linux.
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.create_system = 3  # Identical ZIP metadata on Windows and Linux.
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, source.read_text(encoding='utf-8').replace('\r\n', '\n'))
    checksum = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    (output / (filename + '.sha256')).write_text(f'{checksum}  {filename}\n', encoding='utf-8', newline='\n')

    def variable(name, env, default, description, rules):
        return dict(name=name, env_variable=env, default_value=default, description=description,
                    user_viewable=False, user_editable=False, rules=rules, field_type='text')

    installer = (root / 'packaging/egg/install.py').read_text(encoding='utf-8')
    egg = dict(
        _comment='Generated by packaging/build_ipv4_egg.py. Set the release URL before installation.',
        meta=dict(version='PTDL_v2', update_url=None),
        uuid='54ca43ef-8893-4a45-9d36-a68d99073220',
        name='PortOpenerService IPv4', author='portopener@example.invalid',
        description='Administrator-only, one instance per Wings node. IPv4 UPnP through a configured router URL; outbound HTTPS pairing. Standard bridge networking. Disable IPv6 in node policy. No incoming service port.',
        features=[], docker_images={'Python 3.12': 'ghcr.io/parkervcp/yolks:python_3.12'},
        file_denylist=['data/credentials*', 'data/service*', 'data/state*'], startup='python3 -u /home/container/start_ipv4.py',
        config=dict(files='{}', startup=json.dumps({'done': 'PortOpenerService IPv4 starting'}), logs='{}', stop='^C'),
        scripts=dict(installation=dict(
            script="#!/bin/bash\nset -euo pipefail\npython3 - <<'PORTOPENER_INSTALL'\n" + installer + '\nPORTOPENER_INSTALL\n',
            container='python:3.12-slim-bookworm', entrypoint='bash')),
        variables=[
            variable('Release ZIP URL', 'SERVICE_DOWNLOAD_URL', download_url,
                     'Public HTTPS URL of the versioned IPv4 ZIP; GitHub Releases or your HTTPS file server.', 'required|url'),
            variable('Release SHA-256', 'SERVICE_SHA256', checksum,
                     'Checksum of exactly the ZIP at the download URL. Update with each release.', 'required|string|size:64'),
            variable('Panel HTTPS origin', 'PORT_OPENER_PANEL_URL', '',
                     'Example: https://panel.example.com (no path). Pairing code is entered in the console on first start.', 'required|url'),
        ])
    egg_path = output / 'egg-port-opener-ipv4.json'
    egg_path.write_text(json.dumps(egg, indent=4) + '\n', encoding='utf-8', newline='\n')
    bundled = root / 'plugin/port-opener/resources/releases'
    bundled.mkdir(exist_ok=True)
    if (bundled / filename).exists() and (bundled / filename).read_bytes() != archive_path.read_bytes():
        raise ValueError('Versioned service bundle changed. Bump the version instead of replacing published bytes.')
    shutil.copyfile(archive_path, bundled / filename)
    shutil.copyfile(egg_path, bundled / egg_path.name)
    shutil.copyfile(root / 'service/diagnostics-schema.json', root / 'plugin/port-opener/resources/diagnostics-schema.json')
    (bundled / 'manifest.json').write_text(json.dumps(dict(version=version, filename=filename, sha256=checksum), indent=2) + '\n', encoding='utf-8', newline='\n')
    print(f'Built {archive_path.name}, checksum, and {egg_path.name}')
    print('Download URL: ' + (download_url or 'Automatic for managed installs; standalone export needs an HTTPS URL'))
    return archive_path, egg_path


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--download-url', default='', help='Final public HTTPS release asset URL')
    build(parser.parse_args().download_url)
